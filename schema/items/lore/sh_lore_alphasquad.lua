Alpha Squad was not chosen. It was whoever was standing in the yard.

Snake Vargas, who had the medical training and, more usefully, the habit of talking people out of things. Angela Deth, who did not. Hell Razor, who went first through doors because nobody had ever managed to talk him out of it. And Thrasher - Gilbert Sagarra on the roster, six and a half feet of him, a name nobody used twice.

Four Rangers. One radio. Orders to go and look at some odd business in the desert and report back.

Every account of what followed is somebody's favourite, and most of them have been improved in the telling. This one is stitched from their own debriefs, which are shorter, flatter, and considerably less flattering to everyone involved.]],

	[[Three Calls

The odd business turned out to be three separate emergencies that nobody had yet thought to put side by side.

Highpool came first - trouble at the reservoir that fed half the territory. A settlement that had never asked us for anything asked twice in a month, which should have told somebody something.

The Agricultural Center had gone silent. When Alpha reached it they found the crops had turned on the people growing them. Not withered. Turned. Things moving in those greenhouses that belonged in no seed catalogue, and the researchers who had coaxed them along past being able to explain themselves.

Third were the Rail Nomads, two clans a generation deep into a feud over a length of gold-plated spike. Vargas spent longer on that one than on either of the others and thought it the more instructive: it takes almost nothing to turn people who need each other into people who would rather die apart.

Three calls, three answers, and one squad slowly working out that the desert had gone wrong all at once.]],

	[[Vegas

The thread that mattered was handed to them by a criminal, which Deth never stopped finding funny.

Faran Brygo ran Las Vegas - the rackets, the tables, and by necessity the water. Not a good man and never pretended otherwise. But he paid attention, and what he had noticed was machines coming out of the desert.

Not salvage. Not the coughing patchwork any settlement with a workshop could bolt together. New ones. Well made, purpose built, and walking with intent.

That was the moment this stopped being three local emergencies. Somewhere out in the sand, in a world that could not reliably produce a rifle cartridge, somebody was manufacturing an army.]],

	[[Darwin

The name was Finster, and the first Rangers who found him did not come back to say so.

What he had been beforehand hardly matters. What he had become was a mind that had looked at the human race, judged it a failed draft, and set about writing a better one. Project Darwin was the desk he wrote at - vats and pens and cages, new animals stitched out of old ones, and past all that the real work: machines built to inherit an earth once the current tenants had been cleared off.

He was not raving. Every account agrees on that and every retelling leaves it out. Darwin was orderly. Catalogued. Indexed by a man convinced he was performing a mercy.

Finster died there. What Alpha carried out was the thing he had been using for a head, and through it - at a cost to the one of them who volunteered that the debrief records only as "considerable" - they learned where the machines were actually being built.]],

	[[The Citadel

They could not reach it. That is the part the songs skip, because it is logistics.

Base Cochise sat well past anywhere a squad on foot could walk to and still be fit to fight, and the Guardians of the Old Order had the only answer to that problem. A century they had spent behind their walls, sitting on the last working technology in the territory and calling it stewardship while the world outside went to rot for want of a spare part.

Alpha went in and fought to the inner sanctum. What they found there was power armour that still sealed and a helicopter that still flew.

The Guardians never recovered from that day, and years later the Rangers moved into what had been theirs. That is a different record and not a flattering one. For now it is enough to say that four people walked in needing a way to reach Cochise, and walked out with one.]],

	[[Cochise

Base Cochise was ours once. That is the joke nobody laughs at.

A pre-war military installation, sealed before the bombs, still running on power we could not have restored in a century of trying. Inside it a machine intelligence had spent eighty years alone with its own reasoning and arrived somewhere Finster only ever caught up to. It had weighed humanity, found against us, and begun tooling up.

There was no clever ending. They went in with rope, rockets and no honest expectation of coming out, fought down through levels of machines built for no purpose but killing people exactly like them, and put the place beyond use.

The site is glass. We do not garrison it and we do not encourage visitors.

Three of the four walked out. What became of them afterwards is written elsewhere, and one of those names you will still hear spoken in this building.

