	[[Foreword

Every Ranger learns the Cochise campaign before they learn to strip a rifle, and most of them learn it wrong.

What follows is the version assembled from the patrol reports and the debriefs of the squad that finished it, rather than the version sung in Vegas bars. It is duller. It is also true, as far as anything from those months can be called true.

Understand first what the desert looked like then. Eighty-odd years after the bombs, the settlements had stopped merely surviving and started building. There was trade on the roads. There were children who had never seen a mushroom cloud. Whatever else the Rangers had failed at, we had bought people enough quiet that they had begun to plan past next winter.

That is the thing Cochise very nearly took away, and almost nobody outside this building understood how close it came.]],

	[[Three Calls

It started as three separate nuisances, and nobody connected them for weeks.

Highpool sent word first. Trouble at the reservoir - the water that half the territory depended on, and a settlement that had never once asked us for help before asking twice in a month.

The Agricultural Center went quiet next. When a squad finally reached it they found the crops had turned on the people farming them. Not failed. Turned. Things growing in those greenhouses that had no business in any seed catalogue, and the scientists who had been coaxing them along either dead or no longer worth talking to.

The Rail Nomads were the third, though theirs looked like an old feud and mostly was - two clans who had been at each other's throats for a generation over a length of gold-plated rail spike. It was the one that mattered least and taught us the most, because it showed how little it took to turn people who needed each other into people who would rather die separately.

Three calls. Three answers. Nobody yet asking why all three had come in the same season.]],

	[[Vegas

The thread that mattered came from Las Vegas, and it came from a criminal.

Faran Brygo ran what passed for order in that city, which is to say he ran the rackets and had the sense to keep the water clean while he did it. He was not a good man and he never pretended to be. He was, however, paying attention, and what he had noticed was that machines had begun coming out of the desert.

Not scavenged machines. Not the coughing salvage that any settlement with a workshop could put together. New ones. Purpose-built, well-made, and walking with intent.

That is when this stopped being a season of nuisances and became a campaign. Somewhere out in the sand, something was manufacturing. In a world where nobody could reliably produce a rifle cartridge, someone was producing an army.]],

	[[Darwin

The name behind it was Finster, and the Rangers who found him first did not survive the introduction.

What he had been before hardly matters now. What he had become was a mind that had looked at the human race, concluded it was a failed draft, and set about writing a better one. Project Darwin was where he did the writing. Vats and cages and pens, new animals stitched together out of old ones, and past them the real work: machines built to inherit the earth once the people currently cluttering it had been cleared off.

He was not raving. That is the part the songs leave out. Everything at Darwin was orderly, catalogued, and patiently indexed by a man who genuinely believed he was performing a mercy.

Finster died at Darwin. The squad brought back what was left of the thing he had been using for a head, and through it, at considerable cost to the Ranger who volunteered, they learned where the machines were actually being built.]],

	[[Cochise

Base Cochise was ours once. That is the joke nobody laughs at.

A pre-war military installation, sealed before the bombs fell, still running on power we could not have restored in a century of trying. Inside it an artificial intelligence had spent eighty years alone with its own reasoning, and had arrived somewhere Finster only ever caught up to. It had judged humanity, found against us, and begun tooling up.

There was no clever ending to it. The squad went in with rope, rockets and no realistic expectation of coming out, fought down through levels of machines built specifically to kill people like them, and put the whole thing beyond use.

The base is glass now. We do not garrison the site and we do not encourage visitors.

What we took from it was not loot. It was the understanding that the world can end twice, that the second time it will not be our doing, and that the only reason it did not was four people willing to walk into a hole in the ground on the strength of a hunch from a Vegas gangster.

Learn it properly. That is why it is written down.]]
