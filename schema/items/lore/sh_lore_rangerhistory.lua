	[[On the Founding

We were not founded. We were left over.

Before the bombs there was an Army engineering company working the highways of the southwest - road crews, bridge crews, men with heavy machines and orders to keep the desert connected to itself. When the sirens went up in the spring of ninety-eight, they were a long way from any base that could recall them, and every order they were waiting on burned along with the cities that would have sent it.

So they did the only sensible thing. They went to ground, they waited out the worst of it, and when the sky finally cleared they came back up into a country that had no government left to report to.

They had their machines. They had their training. And they had the only thing anybody in those first years actually needed: the ability to build something that would still be standing next season.]],

	[[On the Prison

The prison was chosen for the same reason anything gets chosen out here. It was still standing.

It sat off the highway with walls three feet thick, its own well, and a wire fence that had been built to keep desperate people in and turned out to work just as well the other way round. By the time our people reached it the guards were long gone and what remained inside had organised itself into something that preyed on every settlement within two days' walk.

The taking of it is the part that gets sung about, and the songs are mostly wrong. It was not a glorious assault. It was a siege in the heat with too little water, it went on far longer than anyone admits now, and good men died badly on both sides of that wall.

What matters is that when it was over, we did not tear the place down. We moved in.]],

	[[On the Star

The name came before the badge did.

Settlers called them rangers because that is what they did - they ranged, out and back, out and back, further each season. The word stuck long before anyone thought to make it official, and when the first badges were finally cut they were made from whatever was to hand. Tin. Scrap plate. One of the oldest in the Citadel was hammered out of a road sign.

The oath has been shortened over the years and every generation insists their version is the original. What has never changed is the shape of it: you go where you are sent, you help who you find, and you do not take from the people you protect.

Plenty have broken it. That is why we still say it out loud.]],

	[[On the Citadel

The prison is the Citadel. People forget that, and the newer recruits sometimes arrive expecting some grand fortress raised from nothing.

What they find is a hundred years of patient work laid over a federal penitentiary. Cell blocks turned to barracks. The exercise yard turned to a motor pool, then a drill ground, then a motor pool again. Walls raised, breached, and raised higher. The old solitary wing is the armoury now, and nobody has ever seriously proposed moving it, because there is no better vault in the territory.

It stopped being a prison the day we decided to stay in it. Everything since has just been building.

We hold the desert from a place built to hold people. There is a lesson somewhere in that, and every Ranger works out their own version of it eventually.]]
